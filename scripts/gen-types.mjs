#!/usr/bin/env node
/**
 * openapi/openapi.json -> packages/sdk/src/generated/types.ts via openapi-typescript.
 *
 * Exits 0 with a message when the spec is absent so `pnpm check` works on a fresh clone before
 * any spec has been synced. With `--check`, exits 1 if the committed output differs from what
 * the spec produces (the CI drift gate).
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const SPEC = resolve(ROOT, 'openapi/openapi.json');
const OUT = resolve(ROOT, 'packages/sdk/src/generated/types.ts');
const check = process.argv.includes('--check');

if (!existsSync(SPEC)) {
  console.log(
    'gen-types: openapi/openapi.json not present; run `pnpm sync-spec` first. Nothing to do.',
  );
  process.exit(0);
}

const banner = [
  '/**',
  ' * GENERATED by scripts/gen-types.mjs from openapi/openapi.json — do not edit.',
  ` * Spec version: ${readFileSync(resolve(ROOT, 'SPEC_VERSION'), 'utf8').trim()}`,
  ' */',
  '',
].join('\n');

const generated = execFileSync(
  'pnpm',
  ['exec', 'openapi-typescript', SPEC, '--export-type', '--alphabetize', '--root-types'],
  { cwd: ROOT, encoding: 'utf8' },
);
const next = banner + generated;

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== next) {
    console.error('gen-types: generated types are out of date; run `pnpm gen:types` and commit.');
    process.exit(1);
  }
  console.log('gen-types: up to date.');
} else {
  writeFileSync(OUT, next);
  console.log(`gen-types: wrote ${OUT}`);
}
